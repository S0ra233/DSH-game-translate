test('检索词法、Unicode 高亮与完整命中门控', () => {
  assert.deepEqual(parseSearchTerms('图书馆 "明天 再见" \\C[2]').terms, ['图书馆', '明天 再见', '\\c[2]']);
  assert.deepEqual(parseSearchTerms('图书馆，明天', true).terms, ['图书馆', '明天']);
  assert.deepEqual(parseSearchTerms('.* [wait]').terms, ['.*', '[wait]']);
  assert.ok(parseSearchTerms('"未结束').error);
  assert.equal(searchParts('e\u0301🙂ALICE', ['é', 'alice']).filter(p => p.match).map(p => p.text).join(''), 'e\u0301ALICE');
  const row = { task: { id: 'body', type: 'dialogue' }, speakerTask: { id: 'name' } };
  assert.deepEqual(rowSearchTerms(row, undefined), { source: [], target: [], sourceName: [], targetName: [] });
  assert.deepEqual(rowSearchTerms(row, { task_id: 'other', matches: [{ task_id: 'body', fields: { source: ['図書館'] } }] }).source, []);
  const accepted = rowSearchTerms(row, { task_id: 'body', matches: [{ task_id: 'body', fields: { target: ['明天'] } }, { task_id: 'name', fields: { source: ['ミナ'] } }] });
  assert.deepEqual(accepted.source, []); assert.deepEqual(accepted.target, ['明天']); assert.deepEqual(accepted.sourceName, ['ミナ']);
});

test('真实 Core + 持久检索：多字段、短词、人名、分页、人工来源、更新、原生 IPC 与被动读取', { timeout: 60000 }, async () => {
  const folder = await mkdtemp(resolve('.test-output/search-')), game = join(folder, 'game');
  await mkdir(join(game, 'data'), { recursive: true });
  await writeFile(join(game, 'data/Actors.json'), JSON.stringify([null, { id: 1, name: 'ミナ', nickname: '', profile: '' }]));
  const texts = ['明日、図書館で会おう。', '図書館の窓を開けよう。', 'また明日、図書館で。', '風が吹いている。'];
  const list = texts.flatMap(text => [{ code: 101, indent: 0, parameters: ['', 0, 0, 2, 'ミナ'] }, { code: 401, indent: 0, parameters: [text] }, { code: 0, indent: 0, parameters: [] }]);
  const original = JSON.stringify({ displayName: '図書館', events: [null, { id: 1, pages: [{ list }] }] });
  await writeFile(join(game, 'data/Map001.json'), original);
  const service = new TranslationService({ dataDirectory: join(folder, 'plugin-data'), pythonExecutable: process.env.DSH_TRANSLATE_PYTHON ?? 'python' });
  const observation = { header: { id: 'search-root', cwd: folder }, events: [], [Symbol.dispose]() {} };
  const agent = { id: 'search-root', session: { header: observation.header, snapshotEvents: () => [] } };
  const call = async (operation, args = {}, options) => (await service.call(agent, operation, args, options)).data;
  const ctx = new Context(); ctx.provide('sessionQuery', { observeSession: async () => observation });
  let ui; const scope = ctx.plugin({ inject: ['sessionQuery'], apply: injected => { ui = new TranslationUi(injected, service); } });
  await scope.await();
  const request = async (action, args = {}) => {
    const result = JSON.parse(await ui.request('search-root', JSON.stringify({ action, ...args })));
    if (!result.ok) throw Error(result.error); return result.value;
  };
  try {
    const begin = await call('begin', { game_dir: game });
    const ready = await call('prepare', { request_id: begin.request.request_id });
    const pid = ready.binding.project_id, work = ready.binding.work_dir;
    const scenes = (await call('scenes', { project_id: pid })).scenes;
    const event = scenes.find(scene => scene.kind === 'event');
    const tasks = (await call('scene', { project_id: pid, scene_id: event.id })).tasks;
    const body = tasks.filter(task => task.type === 'dialogue'); assert.equal(body.length, 4);
    const translations = ['明天在图书馆见。', '今天打开图书馆的窗户。', '明天还在图书馆。', '风正在吹。'];
    const packageValue = await call('package', { project_id: pid, scene_id: event.id });
    const results = packageValue.target_ids.map(id => ({ id, translation: tasks.find(task => task.id === id).type === 'speaker' ? '米娜' : translations[body.findIndex(task => task.id === id)], uncertain: false }));
    const draft = await call('save_draft', { project_id: pid, package_id: packageValue.id, results });
    await call('apply', { project_id: pid, draft_id: draft.draft_id, expected_revision: draft.revision });
    const query = async (fields, extra = {}, page = {}) => request('search-query', { project_id: pid, query: { fields: Object.fromEntries(Object.entries(fields).map(([key, text]) => [key, { text, relation: 'all' }])), ...extra }, ...page });
    const combined = await query({ name: '米娜', target: '明天' }); assert.equal(combined.hits.length, 2);
    const warm = await query({ name: '米娜', target: '明天' }); assert.equal(warm.generation, combined.generation); assert.equal(service.searchWorkers.size, 1);
    assert.equal((await query({ source: '図書館', target: '不匹配的词' })).hits.length, 0);
    const any = await query({ source: '図書館', target: '不匹配的词' }, { relation: 'any' });
    assert.ok(any.hits.length >= 3); assert.ok(any.hits.every(hit => hit.matches.every(match => !match.fields.target)));
    assert.ok((await query({ name: '米' })).hits.length >= 4);
    assert.equal((await query({ target: '明天 图书馆' })).hits.length, 2);
    assert.equal((await query({ target: '.*' })).hits.length, 0);
    const first = await query({ source: '図書館' }, {}, { limit: 1 }); assert.equal(first.has_more, true);
    const second = await query({ source: '図書館' }, {}, { limit: 1, cursor: first.next_cursor }); assert.notEqual(second.hits[0].anchor, first.hits[0].anchor);
    const hit = combined.hits[1];
    const local = await request('search-locate', { project_id: pid, anchor: hit.anchor, task_id: hit.task_id, generation: combined.generation,
      query: { fields: { name: { text: '米娜' }, target: { text: '明天' } } } });
    assert.ok(local.tasks.some(task => task.id === hit.task_id)); assert.ok(local.tasks.some(task => task.type === 'speaker'));
    const current = (await call('scene', { project_id: pid, scene_id: event.id })).tasks.find(task => task.id === body[0].id);
    await request('edit-translation', { project_id: pid, task_id: current.id, translation: '明天一起在图书馆见。', expected_revision: current.revision, expected_source_hash: current.source_hash, expected_translation: current.translation });
    const manual = await query({}, { manual: true }); assert.equal(manual.hits.length, 1); assert.equal(manual.hits[0].task_id, current.id);
    await assert.rejects(query({ source: '図書館' }, {}, { limit: 1, cursor: first.next_cursor }), /更新/);
    const taskFile = join(work, 'tasks.jsonl');
    let saved = (await readFile(taskFile, 'utf8')).trim().split('\n').map(JSON.parse);
    const savedTarget = saved.find(task => task.id === current.id); savedTarget.revision++;
    await writeFile(taskFile, saved.map(task => JSON.stringify(task)).join('\n') + '\n');
    assert.equal((await query({}, { manual: true })).hits.length, 1);
    savedTarget.translation = '替换后的文字。'; savedTarget.revision++;
    await writeFile(taskFile, saved.map(task => JSON.stringify(task)).join('\n') + '\n');
    assert.equal((await query({}, { manual: true })).hits.length, 0);
    assert.equal((await query({ target: '明天' })).hits.length, 1);
    await assert.rejects(request('search-query', { project_id: 'wrong', query: {} }), /不一致/);
    const native = new NativeWindows({ on() {}, get: name => name === 'translationUi' ? ui : undefined }, service);
    const record = { sessionId: 'search-root', lifetime: new AbortController() };
    const nativeResult = await nativeRequest(resolve('native/wpf/TranslationWindow-0.3.7.exe'), 'search-root', 'search-query', { project_id: pid, query: { fields: { target: { text: '明天' } } } }, message => native.dispatch(record, message));
    assert.equal(nativeResult.ok, true, nativeResult.error); assert.equal(nativeResult.value.hits.length, 1);
    assert.equal(await readFile(join(game, 'data/Map001.json'), 'utf8'), original);
    await request('search-close', { project_id: pid });
    const reopened = await query({ target: '明天' }); assert.equal(reopened.hits.length, 1);
    const worker = service.searchWorkers.get('search-root');
    await request('search-close', { project_id: pid }); await worker.done;
    const database = (await readdir(join(folder, 'plugin-data/search'))).find(name => name.endsWith('.sqlite'));
    await writeFile(join(folder, 'plugin-data/search', database), 'damaged derived cache');
    assert.equal((await query({ target: '明天' })).hits.length, 1);
    assert.ok((await readdir(join(folder, 'plugin-data/search'))).some(name => name.includes('.corrupt-')));
    assert.equal(await readFile(join(game, 'data/Map001.json'), 'utf8'), original);
  } finally { await service.dispose(); await scope.dispose(); await ctx.fiber.dispose(); }
});
