import './workspace.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { access, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { build } from 'esbuild';
import { headlessCheck } from './headless-check.mjs';

test('离屏实际设置：下拉开合/退出动画/外点/Esc/键盘、API 填写与中性焦点，均不发模型请求', { timeout: 45000 }, async t => {
  const browser = process.env.DSH_TEST_BROWSER ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
  try { await access(browser); } catch { t.skip('需要本机 Chromium'); return; }
  const folder = await mkdtemp(resolve('.test-output/settings-ui-'));
  const jsx = `import React from 'react';import {createRoot} from 'react-dom/client';
    import {App} from ${JSON.stringify(resolve('src/client/App.jsx').replaceAll('\\', '/'))};
    const calls=[];const api=async(action,args={})=>{calls.push({action,args});
      if(action==='snapshot')return {state:{version:1},stamp:'stable',models:[],modelsAvailable:true};
      if(action==='save-model')return {id:'new-model'};
      throw Error('Unexpected action: '+action);
    };
    localStorage.clear();createRoot(document.getElementById('root')).render(<App api={api} sessionId="settings" nativeChrome/>);
    const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms)),check=(ok,label)=>{if(!ok)throw Error(label)};
    const $=s=>document.querySelector(s),click=async node=>{node.click();await pause(35)},opened=()=>$('.select-popover[data-open=true]');
    const input=(label,text)=>{const el=$('input[aria-label="'+label+'"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,text);el.dispatchEvent(new Event('input',{bubbles:true}));return el};
    (async()=>{
      await pause(200);const more=$('[aria-label="更多操作"]');
      await click(more);check($('.more-menu[data-open=true]'),'open More');
      await click(more);check($('.more-menu[data-open=false]'),'exit retained for animation');
      await click(more);check($('.more-menu[data-open=true]'),'rapid reopen cancels removal');
      await pause(220);check($('.more-menu[data-open=true]'),'rapid reopen remains open');
      await click([...document.querySelectorAll('.menu-item')].find(b=>b.textContent==='设置…'));
      const font=$('[role=combobox][aria-label="字体"]');
      await click(font);check(opened(),'open custom font dropdown');
      const rect=opened().getBoundingClientRect();check(rect.width>150&&rect.height>40,'visible dropdown dimensions');
      await click(font);check(!opened()&&$('.select-popover[data-open=false]'),'same trigger closes');
      await pause(220);check(!$('.select-popover'),'dropdown unmounted after exit');
      await click(font);font.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}));await pause(25);font.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));await pause(40);
      check(font.textContent.includes('衬线字体')&&!opened(),'keyboard commits and closes');
      await click(font);font.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));await pause(40);
      check(!opened()&&$('.dialog-layer[data-open=true]'),'Esc closes only dropdown');
      await click([...document.querySelectorAll('[role=dialog] .segments button')].find(b=>b.textContent==='翻译模型'));
      const protocol=$('[role=combobox][aria-label="协议"]');await click(protocol);check(opened(),'protocol dropdown opens');
      await click([...opened().querySelectorAll('[role=option]')].find(b=>b.textContent.includes('Anthropic')));
      check(protocol.textContent.includes('Anthropic')&&!opened(),'protocol selection commits');
      await click(protocol);
      const address=$('input[aria-label="API 地址"]');address.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}));address.focus();await pause(200);
      check(!opened(),'outside pointer closes');const focus=getComputedStyle(address);
      check(focus.borderColor==='rgb(161, 161, 170)'&&focus.boxShadow.includes('113, 113, 122'),'neutral focus border and soft ring');
      input('名称','  本地测试模型  ');input('API 地址','https://api.example.test/v1');input('API Key','  test-only-secret  ');input('模型名称','  test-model  ');await pause(40);
      $('input[aria-label="API Key"]').focus();address.focus();await pause(40);
      check($('input[aria-label="API Key"]').value==='test-only-secret','API key trims on blur');
      check($('input[aria-label="API Key"]').type==='password','key masked by default');
      const save=$('.model-settings button[type=submit]');save.focus();check(getComputedStyle(save).color==='rgb(255, 255, 255)','primary text visible');
      $('.model-settings').requestSubmit();await pause(100);
      const saved=calls.find(call=>call.action==='save-model');check(saved?.args.protocol==='anthropic-messages'&&saved.args.apiKey==='test-only-secret','save uses existing host API');
      check($('input[aria-label="API Key"]').value==='','key cleared after save');
      check(!JSON.stringify(localStorage).includes('test-only-secret'),'no key in preferences');
      const exit=$('[role=dialog] .close-button');await click(exit);check($('.dialog-layer[data-open=false]'),'dialog exit retained');
      await pause(220);check(!$('[role=dialog]'),'dialog removed after exit');
      check(!calls.some(c=>!['snapshot','save-model'].includes(c.action)),'no initialize/model/translation requests');
      check(location.hash==='','controls keep native document identity');
      document.getElementById('result').textContent=JSON.stringify({ok:true,modelRequests:0,actualDSH:false});
    })().catch(error=>document.getElementById('result').textContent=JSON.stringify({error:error.message,stack:error.stack}));`;
  const source = join(folder, 'check.jsx'); await writeFile(source, jsx);
  await build({ entryPoints: [source], outfile: join(folder, 'check.js'), bundle: true, platform: 'browser', format: 'iife', jsx: 'transform', define: { 'process.env.NODE_ENV': '"production"' } });
  const html = join(folder, 'check.html');
  await writeFile(html, `<!doctype html><html data-material-host="native"><meta charset="utf-8"><style>html,body,#root{height:100%;margin:0}${await readFile('src/client/surface.css', 'utf8')}</style><div id="root"></div><pre id="result">pending</pre><script src="./check.js"></script></html>`);
  const output = await headlessCheck(browser, folder, html); await writeFile(join(folder, 'result.html'), output);
  const encoded = /<pre id="result">([^<]*)<\/pre>/.exec(output)?.[1]; assert.ok(encoded && encoded !== 'pending');
  const report = JSON.parse(encoded.replaceAll('&quot;', '"').replaceAll('&gt;', '>').replaceAll('&lt;', '<').replaceAll('&amp;', '&'));
  assert.equal(report.ok, true, report.error);
});
